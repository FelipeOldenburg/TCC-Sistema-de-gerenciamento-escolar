CREATE TABLE IF NOT EXISTS reorganizacao_salas_relacionadas (
  reorganizacao_id INTEGER NOT NULL REFERENCES reorganizacoes(id) ON DELETE CASCADE,
  sala             VARCHAR(50) NOT NULL,
  PRIMARY KEY (reorganizacao_id, sala)
