CREATE TABLE IF NOT EXISTS sessoes (
  token_hash  CHAR(64) PRIMARY KEY,
  usuario_id  INTEGER NOT NULL REFERENCES usuarios(id) ON DELETE CASCADE,
  expires_at  TIMESTAMP NOT NULL,
  created_at  TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX IF NOT EXISTS idx_sessoes_usuario
  ON sessoes (usuario_id);

CREATE INDEX IF NOT EXISTS idx_sessoes_expiracao
  ON sessoes (expires_at);

CREATE TABLE IF NOT EXISTS blocos (
  id          INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  instituicao_id INTEGER NOT NULL,
  nome        VARCHAR(120) NOT NULL,
  descricao   TEXT NULL,
  created_at  TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at  TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT uq_blocos_instituicao_nome UNIQUE (instituicao_id, nome)
