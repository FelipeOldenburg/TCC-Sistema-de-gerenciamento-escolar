CREATE TABLE IF NOT EXISTS salas (
  id                    INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  instituicao_id         INTEGER NOT NULL,
  bloco_id              INTEGER NOT NULL REFERENCES blocos(id) ON DELETE RESTRICT,
  nome                  VARCHAR(120) NOT NULL,
  andar                 VARCHAR(40) NOT NULL,
  capacidade            INTEGER NULL CHECK (capacidade IS NULL OR capacidade >= 0),
  tipo                  VARCHAR(80) NOT NULL,
  status                VARCHAR(20) NOT NULL DEFAULT 'ATIVA' CHECK (status IN ('ATIVA', 'INATIVA', 'MANUTENCAO')),
  acessivel             BOOLEAN NOT NULL DEFAULT FALSE,
  possui_computadores   BOOLEAN NOT NULL DEFAULT FALSE,
  possui_data_show      BOOLEAN NOT NULL DEFAULT FALSE,
  possui_internet       BOOLEAN NOT NULL DEFAULT FALSE,
  possui_ar_condicionado BOOLEAN NOT NULL DEFAULT FALSE,
  observacoes           TEXT NULL,
  created_at            TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at            TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT uq_salas_instituicao_bloco_nome UNIQUE (instituicao_id, bloco_id, nome)
);

CREATE INDEX IF NOT EXISTS idx_salas_recursos
  ON salas (possui_computadores, possui_data_show, possui_internet, possui_ar_condicionado);

CREATE INDEX IF NOT EXISTS idx_salas_capacidade
  ON salas (capacidade);

