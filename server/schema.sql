INSERT INTO grupos_academicos (instituicao_id, tipo, nome)
SELECT DISTINCT h.instituicao_id, grupo.tipo, grupo.nome
  FROM horarios_importados h
 CROSS JOIN LATERAL (VALUES
   ('CURSO', NULLIF(TRIM(h.curso), '')),
   ('ANO', NULLIF(TRIM(h.ano), '')),
   ('TURMA', NULLIF(TRIM(h.turma), ''))
 ) AS grupo(tipo, nome)
 WHERE grupo.nome IS NOT NULL
ON CONFLICT (instituicao_id, tipo, nome) DO NOTHING;

