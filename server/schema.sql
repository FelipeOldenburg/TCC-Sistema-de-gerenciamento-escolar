CREATE TABLE IF NOT EXISTS alunos (
  id          INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  instituicao_id INTEGER NOT NULL,
  nome        VARCHAR(120) NOT NULL,
  ano         VARCHAR(20)  NOT NULL,
  turma       VARCHAR(30)  NOT NULL,
  curso       VARCHAR(80)  NOT NULL,
  created_at  TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX IF NOT EXISTS idx_alunos_lookup
  ON alunos (nome, ano, turma, curso);

CREATE TABLE IF NOT EXISTS reorganizacoes (
  id            INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  aluno_id      INTEGER NOT NULL REFERENCES alunos(id) ON DELETE CASCADE,
  problema      TEXT NOT NULL,
  arquivo_nome  VARCHAR(255) NULL,
  arquivo_dados BYTEA NULL,
  data          DATE NOT NULL,
  created_at    TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX IF NOT EXISTS idx_reorganizacoes_data
  ON reorganizacoes (data, id);

CREATE INDEX IF NOT EXISTS idx_reorganizacoes_aluno
