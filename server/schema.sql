CREATE TABLE IF NOT EXISTS instituicoes (
  id                 INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  slug               VARCHAR(60) NOT NULL UNIQUE,
  nome               VARCHAR(120) NOT NULL,
  nome_admin         VARCHAR(120) NOT NULL,
  nome_sistema       VARCHAR(160) NOT NULL,
  subtitulo_admin    VARCHAR(160) NOT NULL,
  logo_url           VARCHAR(500) NULL,
  cor_primaria_hsl   VARCHAR(40) NOT NULL,
  cor_acento_hsl     VARCHAR(40) NOT NULL,
  cor_header_hsl     VARCHAR(40) NOT NULL,
  cor_nav_hsl        VARCHAR(40) NOT NULL,
  cor_nav_ativa_hsl  VARCHAR(40) NOT NULL,
  ativo              BOOLEAN NOT NULL DEFAULT TRUE,
  created_at         TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at         TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

